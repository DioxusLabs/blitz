//! Two-way conversions between [`keyboard-types`](https://docs.rs/keyboard-types) v0.7 and v0.8 types.
//!
//! The [`to_08`] module converts v0.7 types to v0.8 types, and the [`to_07`]
//! module converts v0.8 types to v0.7 types.
//!
//! All conversions are lossless except for [`Code`](kt08::Code) variants that
//! only exist in v0.8 (e.g. `KeyboardBacklightToggle`), which map to
//! [`Code::Unidentified`](kt07::Code::Unidentified) when converting to v0.7.

pub use kt07;
pub use kt08;

