    /// Convert a v0.7 [`KeyboardEvent`](old::KeyboardEvent) to a v0.8 [`KeyboardEvent`](new::KeyboardEvent).
    pub fn keyboard_event(event: old::KeyboardEvent) -> new::KeyboardEvent {
        new::KeyboardEvent {
            state: key_state(event.state),
            key: key(event.key),
            code: code(event.code),
            location: location(event.location),
            modifiers: modifiers(event.modifiers),
            repeat: event.repeat,
            is_composing: event.is_composing,
        }
    }

    /// Convert a v0.7 [`CompositionEvent`](old::CompositionEvent) to a v0.8 [`CompositionEvent`](new::CompositionEvent).
    pub fn composition_event(event: old::CompositionEvent) -> new::CompositionEvent {
        new::CompositionEvent {
            state: composition_state(event.state),
            data: event.data,
        }
    }

    /// Convert a v0.7 [`CompositionState`](old::CompositionState) to a v0.8 [`CompositionState`](new::CompositionState).
    pub fn composition_state(state: old::CompositionState) -> new::CompositionState {
        match state {
            old::CompositionState::Start => new::CompositionState::Start,
            old::CompositionState::Update => new::CompositionState::Update,
            old::CompositionState::End => new::CompositionState::End,
        }
    }

    /// Convert a v0.7 [`KeyState`](old::KeyState) to a v0.8 [`KeyState`](new::KeyState).
    pub fn key_state(state: old::KeyState) -> new::KeyState {
        match state {
            old::KeyState::Down => new::KeyState::Down,
            old::KeyState::Up => new::KeyState::Up,
        }
    }

    /// Convert a v0.7 [`Location`](old::Location) to a v0.8 [`Location`](new::Location).
    pub fn location(location: old::Location) -> new::Location {
        match location {
            old::Location::Standard => new::Location::Standard,
            old::Location::Left => new::Location::Left,
            old::Location::Right => new::Location::Right,
            old::Location::Numpad => new::Location::Numpad,
        }
    }

    /// Convert v0.7 [`Modifiers`](old::Modifiers) to v0.8 [`Modifiers`](new::Modifiers).
    pub fn modifiers(modifiers: old::Modifiers) -> new::Modifiers {
        new::Modifiers::from_bits_truncate(modifiers.bits())
    }

