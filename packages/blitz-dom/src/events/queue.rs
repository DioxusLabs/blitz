use std::collections::VecDeque;

use blitz_traits::events::{DomEvent, DomEventData, EventDispatchSource};
use blitz_traits::node_id::NodeId;

/// The events queued on a document, waiting to be dispatched by an
/// [`EventDriver`](crate::EventDriver).
#[derive(Default)]
pub(crate) struct EventQueue {
    events: VecDeque<DomEvent>,
}

impl EventQueue {
    /// Queue an event.
    ///
    /// A `scroll` or `resize` event replaces an event of the same kind for the same target
    /// at the back of the queue, so several of them queued before the queue is drained
    /// dispatch one event with the latest data. Only the back of the queue is considered,
    /// which keeps these events in order relative to other events.
    pub(crate) fn push(&mut self, event: DomEvent) {
        if matches!(
            event.data,
            DomEventData::Scroll(_) | DomEventData::Resize(_)
        ) && let Some(last) = self.events.back_mut()
            && std::mem::discriminant(&last.data) == std::mem::discriminant(&event.data)
            && last.target == event.target
            && last.source == event.source
        {
            *last = event;
            return;
        }

        // Bound the queue in case the embedder never drains it
        const MAX_PENDING_EVENTS: usize = 1024;
        if self.events.len() >= MAX_PENDING_EVENTS {
            self.events.pop_front();
        }
        self.events.push_back(event);
    }

    /// [Queue](Self::push) an event generated by the engine itself
    pub(crate) fn push_ua_event(&mut self, target: NodeId, data: DomEventData) {
        self.push(DomEvent::new(target, data, EventDispatchSource::UserAgent));
    }

    pub(crate) fn pop(&mut self) -> Option<DomEvent> {
        self.events.pop_front()
    }

    pub(crate) fn is_empty(&self) -> bool {
        self.events.is_empty()
    }
}
